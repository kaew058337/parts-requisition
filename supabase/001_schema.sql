create extension if not exists pgcrypto;

-- ---------- ใบเบิก (ชีท เบิก) ----------
create table if not exists requisitions (
  seq              bigint generated by default as identity primary key,
  doc_no           text not null,                 -- หมายเลขการเบิก 9 หลัก
  part_no          text not null,
  name             text not null default '',
  qty              numeric not null check (qty > 0),
  unit             text not null default '',
  req_date         date not null,
  pay_date         date,                          -- วันที่รับครบ (null = ค้างจ่าย)
  cancelled        boolean not null default false,
  cancel_reason    text not null default '',
  machine          text not null default '',      -- 70201..70207 / ALL SAAB / FLY AWAY KIT 1-2
  urgency          text not null default '',
  issue_text       text not null default '',      -- ข้อขัดข้อง
  req_rank         text not null default '',
  req_name         text not null default '',
  req_position     text not null default '',
  item_type        text not null default 'SP' check (item_type in ('LRU','SP','LRU(TCI)','SP(TCI)')),
  tci_install_date date,
  tai_status       text not null default '',
  tai_note         text not null default '',
  tai_po           text not null default '',
  tai_supplier     text not null default '',
  tai_due          text not null default '',
  tai_asof         timestamptz,
  created_at       timestamptz not null default now()
);
create index if not exists requisitions_doc_idx  on requisitions (doc_no);
create index if not exists requisitions_part_idx on requisitions (part_no);
create index if not exists requisitions_open_idx on requisitions (req_date) where pay_date is null and not cancelled;

-- ---------- รับ (ชีท รับ + รับคืนเข้าคลัง) ----------
create table if not exists receipts (
  seq            bigint generated by default as identity primary key,   -- ลำดับรับ
  doc_no         text not null default '',        -- เลขเอกสารการเบิก ('' = ยอดยกมา/รับก่อนเบิก)
  card_id        text not null default '',        -- เลขเอกสารส่งมอบ TAI
  part_no        text not null,
  name           text not null default '',
  serial_no      text not null default '',
  item_type      text not null default 'SP' check (item_type in ('LRU','SP','LRU(TCI)','SP(TCI)')),
  item_group     text not null default '' check (item_group in ('','สารเคมี')),   -- กลุ่มพัสดุ (แยกจากประเภท)
  qty            numeric not null check (qty > 0),
  unit           text not null default '',
  unit_price     numeric,
  total_price    numeric generated always as (qty * coalesce(unit_price, 0)) stored,
  cond           text not null default '',
  notified_date  date,
  urgency        text not null default '',
  due_date       date,
  received_date  date,
  over_days      numeric,
  tail_no        text not null default '',
  tci            text not null default '',
  expire_date    date,
  location       text not null default '',
  receiver       text not null default '',
  note           text not null default '',
  source         text not null default '',        -- ใบเบิก / ยอดยกมา / รับก่อนเบิก / คืนเข้าคลัง (SRC_*)
  ref_seq        bigint,                          -- อ้างอิง (โอนจากล็อต / ล็อตที่คืน)
  created_at     timestamptz not null default now()
);
create index if not exists receipts_part_idx  on receipts (part_no);
create index if not exists receipts_doc_idx   on receipts (doc_no);
create index if not exists receipts_loc_idx   on receipts (location);
create index if not exists receipts_serial_idx on receipts (serial_no) where serial_no <> '';
create index if not exists receipts_date_idx  on receipts (received_date);

-- ---------- จ่าย (ชีท จ่าย) : เพิ่มอย่างเดียว ----------
create table if not exists issues (
