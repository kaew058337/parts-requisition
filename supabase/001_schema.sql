  receipt_seq  bigint not null references receipts (seq),
  part_no      text not null,
  name         text not null default '',
  serial_no    text not null default '',
  qty          numeric not null check (qty > 0),
  unit         text not null default '',
  tail_no      text not null default '',
  technician   text not null default '',
  note         text not null default '',
  created_by   text not null default '',
  created_at   timestamptz not null default now()
);
create index if not exists issues_receipt_idx on issues (receipt_seq);
create index if not exists issues_doc_idx     on issues (doc_no);
create index if not exists issues_date_idx    on issues (issue_date);

