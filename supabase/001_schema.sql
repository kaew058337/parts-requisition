--  แปลงจากชีท Google Sheets เดิม  -  รันใน Supabase > SQL Editor
--  หลักการ
--   * "ลำดับ" ของแต่ละชีทเดิมเก็บเป็น seq (bigint) ใช้เลขเดิมตอนนำเข้า เพื่อให้การอ้างอิงข้ามตาราง (ลำดับรับ, เลขเอกสาร) ยังตรง
--   * ledger (รับ / จ่าย) เพิ่มอย่างเดียว ยอดคลังคำนวณจากสองตารางนี้ (ทำเป็น view/ฟังก์ชันในไฟล์ 002)
--   * ยกเลิก = ย้ายแถวไปตาราง cancelled_records (หลักฐาน) แล้วลบจากตารางหลัก ผ่านฟังก์ชันเท่านั้น (ผู้ใช้ผ่าน anon ลบตรงๆ ไม่ได้)
--   * seq ใช้ sequence ของฐานข้อมูล -> ไม่มีทางใช้เลขซ้ำ (แทนการคัดลอกแถวในชีทที่เคยทำให้ลำดับซ้ำ)
