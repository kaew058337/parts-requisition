-- ---------- ความปลอดภัย (RLS) ----------
-- เลือกแบบไม่ล็อกอิน : anon อ่าน/เพิ่ม/แก้ได้ แต่ "ลบตรงๆ ไม่ได้" (การยกเลิกทำผ่านฟังก์ชัน security definer ในไฟล์ 002)
-- หมายเหตุ: ใครมีลิงก์เว็บ+คีย์ anon ก็เขียนข้อมูลได้ ควรเก็บลิงก์เป็นความลับ และมีสำรองข้อมูลรายวัน
do $$
declare t text;
begin
  foreach t in array array['requisitions','receipts','issues','returns_out','loans','counts','claims','requesters','technicians','receivers',
                           'holidays','shelf_cells','move_history','kit_requirements','cancelled_records','activity_log']
  loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists "app_select" on %I', t);
    execute format('drop policy if exists "app_insert" on %I', t);
    execute format('drop policy if exists "app_update" on %I', t);
    execute format('create policy "app_select" on %I for select to anon using (true)', t);
    execute format('create policy "app_insert" on %I for insert to anon with check (true)', t);
    -- ledger (receipts/issues/cancelled_records/activity_log) ห้ามแก้ตรงๆ ให้แก้ผ่านฟังก์ชันเท่านั้น
    if t not in ('issues','cancelled_records','activity_log') then
      execute format('create policy "app_update" on %I for update to anon using (true) with check (true)', t);
    end if;
  end loop;
end $$;
