-- ---------- 1) ความคืบหน้า TAI (Edge Function อ่านไฟล์ แล้วส่งแถวมาที่นี่) ----------
-- rows = [{doc, part, name, po, supplier, note, stage, date(YYYY-MM-DD หรือ null)}] ; คืนสรุป (ตรงกับ applyTai_ เดิม)
create or replace function fn_tai_apply(rows jsonb, asof date default fn_today()) returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  x jsonb; r record; matched int := 0; unmatched int := 0; finished int := 0; changed text[] := '{}'; delivered text[] := '{}'; missing text[] := '{}';
  seen text[] := '{}'; done boolean;
begin
  perform fn_lock();
  for x in select e from jsonb_array_elements(coalesce(rows, '[]'::jsonb)) e loop
    select q.seq, q.doc_no, q.tai_status, q.cancelled, q.pay_date, greatest(q.qty - coalesce(g.have, 0), 0) as remain
      into r from requisitions q
      left join lateral (select sum(c.qty) have from receipts c where c.source = 'ใบเบิก' and c.doc_no = q.doc_no and c.part_no = q.part_no) g on true
     where q.doc_no = x->>'doc' and not q.cancelled order by q.seq limit 1;
    if not found then unmatched := unmatched + 1; continue; end if;
    seen := array_append(seen, r.doc_no);
    if r.pay_date is not null or r.remain <= 0 then finished := finished + 1; continue; end if;
    matched := matched + 1;
    if coalesce(r.tai_status, '') <> '' and r.tai_status <> x->>'stage' then changed := array_append(changed, r.doc_no || ': ' || r.tai_status || ' → ' || (x->>'stage')); end if;
    if x->>'stage' = 'นำจ่ายคลังฝูงแล้ว' then delivered := array_append(delivered, r.doc_no || ' ' || coalesce(nullif(x->>'part',''), x->>'name')); end if;
    update requisitions set tai_status = coalesce(x->>'stage',''), tai_note = coalesce(x->>'note',''), tai_po = coalesce(x->>'po',''),
           tai_supplier = coalesce(x->>'supplier',''), tai_due = coalesce(x->>'date',''), tai_asof = (asof::timestamp at time zone 'Asia/Bangkok')
     where seq = r.seq;
  end loop;
  -- ใบเบิกที่เคยมีข้อมูล TAI แต่หายจากไฟล์ใหม่ และยังค้างรับ
  for r in select q.doc_no from requisitions q
           left join lateral (select sum(c.qty) have from receipts c where c.source = 'ใบเบิก' and c.doc_no = q.doc_no and c.part_no = q.part_no) g on true
           where q.tai_status <> '' and not q.cancelled and q.pay_date is null and q.qty - coalesce(g.have, 0) > 0 loop
    if not (r.doc_no = any(seen)) then missing := array_append(missing, r.doc_no); end if;
  end loop;
  -- ล้างข้อมูล TAI ของใบเบิกที่รับครบ/ยกเลิก/จ่ายแล้ว
  update requisitions q set tai_status = '', tai_note = '', tai_po = '', tai_supplier = '', tai_due = '', tai_asof = null
   where (q.tai_status <> '' or q.tai_note <> '' or q.tai_po <> '' or q.tai_supplier <> '' or q.tai_due <> '' or q.tai_asof is not null)
     and (q.cancelled or q.pay_date is not null
          or q.qty - coalesce((select sum(c.qty) from receipts c where c.source = 'ใบเบิก' and c.doc_no = q.doc_no and c.part_no = q.part_no), 0) <= 0);
  perform fn_log('ไลน์', 'นำเข้า', '', 'อ่านความคืบหน้า TAI: ตรงกัน ' || matched || ' ไม่ตรง ' || unmatched);
  return jsonb_build_object('matched', matched, 'unmatched', unmatched, 'finished', finished, 'changed', to_jsonb(changed), 'delivered', to_jsonb(delivered), 'missing', to_jsonb(missing));
end $$;

-- ---------- 2) รายการ TCI รอเบิก ----------
create table if not exists tci_inbox (
  id          bigint generated by default as identity primary key,
  part_no     text not null,
  name        text not null default '',
  qty         numeric not null check (qty > 0),
  machine     text not null,
  install     date not null,
  serial_no   text not null default '',
  item_type   text not null default 'SP(TCI)',
  issue_text  text not null default '',
  src_file    text not null default '',
  status      text not null default 'รอเบิก' check (status in ('รอเบิก','เบิกแล้ว','ลบทิ้ง')),
  doc_no      text not null default '',
  created_at  timestamptz not null default now(),
  done_at     timestamptz
);
create index if not exists tci_inbox_status_idx on tci_inbox (status);
alter table tci_inbox enable row level security;
revoke all on tci_inbox from anon, authenticated;

-- Edge Function ส่งรายการที่อ่านได้มา ; ข้ามรายการที่ซ้ำกับที่รอเบิกอยู่ หรือที่มีใบเบิกแล้ว (Part + เครื่อง + วันติดตั้ง + จำนวน)
create or replace function fn_tci_ingest(items jsonb, src text default '') returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare x jsonb; added int := 0; dup int := 0; d date;
begin
  perform fn_lock();
  for x in select e from jsonb_array_elements(coalesce(items, '[]'::jsonb)) e loop
    d := fn_date(x->>'install');
    if d is null or coalesce(fn_num(x->>'qty'), 0) <= 0 or btrim(coalesce(x->>'part','')) = '' then continue; end if;
    if exists (select 1 from tci_inbox t where t.status = 'รอเบิก' and t.part_no = x->>'part' and t.machine = x->>'machine' and t.install = d and t.qty = fn_num(x->>'qty') and t.serial_no = coalesce(x->>'sn',''))
       or exists (select 1 from requisitions r where not r.cancelled and r.part_no = x->>'part' and r.machine = x->>'machine' and r.tci_install_date = d and r.qty = fn_num(x->>'qty'))
    then dup := dup + 1; continue; end if;
    insert into tci_inbox(part_no, name, qty, machine, install, serial_no, item_type, issue_text, src_file)
    values (x->>'part', coalesce(x->>'name',''), fn_num(x->>'qty'), x->>'machine', d, coalesce(x->>'sn',''),
            case when coalesce(x->>'sn','') <> '' then 'LRU(TCI)' else 'SP(TCI)' end, coalesce(x->>'issue',''), coalesce(src,''));
    added := added + 1;
  end loop;
  perform fn_log('ไลน์', 'นำเข้า', '', 'อ่านตาราง TCI จากไลน์ ' || added || ' รายการ (ซ้ำ ' || dup || ') ' || coalesce(src,''));
  return jsonb_build_object('added', added, 'dup', dup, 'pending', (select count(*) from tci_inbox where status = 'รอเบิก'));
end $$;

create or replace function rpc_get_tci_inbox() returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(jsonb_build_object('id', id, 'part', part_no, 'name', name, 'qty', qty, 'machine', machine, 'install', to_char(install, 'YYYY-MM-DD'),
      'installTh', fn_thai(install), 'sn', serial_no, 'itemType', item_type, 'issue', issue_text, 'src', src_file) order by install, machine, id), '[]'::jsonb)
  from tci_inbox where status = 'รอเบิก'
$$;

create or replace function rpc_tci_inbox_drop(p jsonb) returns jsonb language plpgsql security definer set search_path = public as $$
declare n int;
begin
  update tci_inbox set status = 'ลบทิ้ง', done_at = now()
   where status = 'รอเบิก' and id in (select (e)::bigint from jsonb_array_elements_text(coalesce(p->'ids','[]'::jsonb)) e);
  get diagnostics n = row_count;
  perform fn_log(p->>'by', 'นำเข้า', '', 'ลบรายการ TCI รอเบิก ' || n || ' รายการ');
  return jsonb_build_object('dropped', n);
end $$;

-- ออกใบเบิกจากรายการรอเบิก (1 รายการ = 1 ใบเบิก) ; p = {ids, fullName, rank, position, urgency, date, by, token}
create or replace function rpc_tci_inbox_issue(p jsonb) returns jsonb language plpgsql security definer set search_path = public as $$
declare tk text := nullif(btrim(coalesce(p->>'token','')),''); res jsonb; t record; r jsonb; docs jsonb := '[]'::jsonb;
begin
  perform fn_lock();
  if tk is not null then select result into res from idempotency where token = tk; if found then return res; end if; end if;
  if btrim(coalesce(p->>'fullName','')) = '' then raise exception 'กรุณาเลือกผู้เบิก'; end if;
  for t in select * from tci_inbox where status = 'รอเบิก' and id in (select (e)::bigint from jsonb_array_elements_text(coalesce(p->'ids','[]'::jsonb)) e) order by install, machine, id loop
    r := fn_requisition_core(jsonb_build_object('date', p->>'date', 'urgency', coalesce(p->>'urgency','เบิกธรรมดา'), 'machine', t.machine,
        'issue', concat_ws(' · ', nullif(t.issue_text,'')), 'rank', coalesce(p->>'rank',''), 'fullName', p->>'fullName', 'position', coalesce(p->>'position',''), 'by', p->>'by',
        'requireInstall', true,
        'items', jsonb_build_array(jsonb_build_object('part', t.part_no, 'name', t.name, 'qty', t.qty, 'unit', 'EA', 'itemType', t.item_type, 'install', to_char(t.install, 'YYYY-MM-DD')))));
    update tci_inbox set status = 'เบิกแล้ว', doc_no = r->>'docNo', done_at = now() where id = t.id;
    docs := docs || jsonb_build_object('docNo', r->>'docNo', 'part', t.part_no, 'name', t.name, 'qty', t.qty, 'unit', 'EA', 'itemType', t.item_type,
                      'machine', t.machine, 'issue', t.issue_text);
  end loop;
  if jsonb_array_length(docs) = 0 then raise exception 'ไม่พบรายการที่เลือก (อาจถูกเบิกหรือลบไปแล้ว)'; end if;
  res := jsonb_build_object('docNo', docs->0->>'docNo', 'docs', docs, 'count', jsonb_array_length(docs));
  if tk is not null then insert into idempotency(token, result) values (tk, res) on conflict do nothing; end if;
  return res;
end $$;

-- ---------- 3) ข้อมูลรายงานสัปดาห์ (หน้ารายงานในเว็บเรียกใช้) ----------
create or replace function rpc_get_weekly(p jsonb default '{}'::jsonb) returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
  d date := coalesce(fn_date(p->>'date'), fn_today()); w1 date := d - ((extract(isodow from d)::int) - 1); w2 date := w1 + 6; n1 date := w1 + 7; n2 date := w1 + 13;
  dash jsonb := rpc_get_dashboard(to_char(d, 'YYYY-MM')); tai jsonb; nx jsonb; rv jsonb; rq jsonb; iss jsonb;
begin
  select coalesce(jsonb_agg(jsonb_build_object('doc', doc_no, 'part', part_no, 'name', name, 'machine', machine, 'urg', urgency, 'type', item_type, 'remain', remain,
      'label', t->>'label', 'level', t->>'level', 'po', t->>'po', 'supplier', t->>'supplier', 'asof', t->>'asof', 'stale', (t->>'stale')::boolean)
      order by case t->>'level' when 'bad' then 0 when 'warn' then 1 else 2 end, case when urgency = 'AOG' then 0 else 1 end, doc_no), '[]'::jsonb) into tai
  from (select v.*, fn_tai_obj((select q from requisitions q where q.seq = v.seq), v.install) t from v_req_status v where v.remain > 0) z where t is not null;

  select coalesce(jsonb_agg(jsonb_build_object('install', fn_thai(install), 'part', part_no, 'name', name, 'machine', machine, 'qty', qty, 'remain', remain, 'doc', doc_no,
      'tai', coalesce(t->>'label','')) order by install, remain desc), '[]'::jsonb) into nx
  from (select v.*, case when v.remain > 0 then fn_tai_obj((select q from requisitions q where q.seq = v.seq), v.install) end t from v_req_status v
         where v.item_type in ('LRU(TCI)','SP(TCI)') and v.install between n1 and n2) z;

  select coalesce(jsonb_agg(jsonb_build_object('date', fn_thai(dt), 'doc', doc_no, 'part', part_no, 'name', nm, 'machine', mc, 'qty', q) order by dt, doc_no), '[]'::jsonb) into rv
  from (select c.doc_no, c.part_no, max(c.received_date) dt, max(coalesce(nullif(c.name,''), r.name)) nm, max(coalesce(r.machine,'')) mc, sum(c.qty) q
          from receipts c left join requisitions r on r.doc_no = c.doc_no and r.part_no = c.part_no and not r.cancelled
         where c.source = 'ใบเบิก' and c.doc_no <> '' and c.received_date between w1 and w2 group by c.doc_no, c.part_no) z;

  select coalesce(jsonb_agg(jsonb_build_object('date', fn_thai(req_date), 'doc', doc_no, 'part', part_no, 'name', name, 'qty', qty, 'machine', machine, 'urg', urgency, 'type', item_type)
      order by req_date, doc_no), '[]'::jsonb) into rq from requisitions where not cancelled and req_date between w1 and w2;

  select coalesce(jsonb_agg(jsonb_build_object('date', fn_thai(issue_date), 'doc', case when doc_no ~ '^\d{9}$' then doc_no else '-' end, 'part', part_no, 'name', name, 'sn', serial_no,
      'qty', qty, 'tail', tail_no, 'tech', technician) order by issue_date, seq), '[]'::jsonb) into iss from issues where issue_date between w1 and w2;

  return jsonb_build_object('today', fn_thai(d), 'w1', fn_thai(w1), 'w2', fn_thai(w2), 'n1', fn_thai(n1), 'n2', fn_thai(n2), 'month', to_char(d, 'YYYY-MM'),
    'tciSum', dash->'tciSum', 'tci', dash->'tci', 'tai', tai, 'next', nx, 'recv', rv, 'reqs', rq, 'iss', iss);
end $$;

-- ข้อความสั้นสำหรับไลน์ (ลิงก์รายงานต่อท้ายโดย Edge Function)
create or replace function fn_line_weekly_text(today date default fn_today()) returns text language plpgsql volatile security definer set search_path = public as $$
declare w jsonb := rpc_get_weekly(jsonb_build_object('date', to_char(today, 'YYYY-MM-DD'))); s jsonb := w->'tciSum'; miss int; tb int; L text[] := '{}';
begin
  select count(*) into miss from jsonb_array_elements(w->'next') e where (e->>'remain')::numeric > 0;
  select count(*) into tb from jsonb_array_elements(w->'tai') e where e->>'level' = 'bad';
  L := array['📄 รายงานสรุปประจำสัปดาห์ ' || (w->>'w1') || ' – ' || (w->>'w2'), '────────────',
    '📊 TCI เดือนนี้: รับแล้ว ' || coalesce(s->>'done','0') || '/' || coalesce(s->>'total','0') || case when (s->>'pending')::int > 0 then ' · ค้างรับ ' || (s->>'pending') else '' end
      || case when (s->>'overdue')::int > 0 then ' · เกินวันติดตั้ง ' || (s->>'overdue') else '' end,
    '🚚 พัสดุค้างจ่าย (TAI) ' || jsonb_array_length(w->'tai') || ' รายการ' || case when jsonb_array_length(w->'tai') > 0 then ' · ต้องติดตาม ' || tb else '' end,
    '🔧 ติดตั้งสัปดาห์หน้า ' || jsonb_array_length(w->'next') || ' รายการ' || case when jsonb_array_length(w->'next') > 0 then case when miss > 0 then ' · ของยังไม่มา ' || miss else ' · ของมาครบ' end else '' end,
    '📦 รับ ' || jsonb_array_length(w->'recv') || ' · เบิก ' || jsonb_array_length(w->'reqs') || ' · จ่าย ' || jsonb_array_length(w->'iss') || ' รายการ'];
  return array_to_string(L, E'\n');
end $$;

-- วันทำงานสุดท้ายของสัปดาห์ : รายงานสัปดาห์ + แจ้งด่วน ; วันอื่น : เฉพาะแจ้งด่วน ; วันหยุด : ว่าง
-- (ลิงก์รายงานต่อท้ายโดย Edge Function เมื่อ weekly = true)
create or replace function fn_line_daily2(today date default fn_today()) returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare wk boolean; urgent text;
begin
  if not fn_is_workday(today) then return jsonb_build_object('text', '', 'weekly', false); end if;
  wk := fn_last_workday_of_week(today);
  urgent := fn_line_digest(today, true);
  if wk then return jsonb_build_object('text', fn_line_weekly_text(today) || case when urgent <> '' then E'\n\n' || urgent else '' end, 'weekly', true); end if;
  return jsonb_build_object('text', urgent, 'weekly', false);
end $$;

-- ---------- สิทธิ์ ----------
revoke all on function fn_tai_apply(jsonb, date), fn_tci_ingest(jsonb, text), fn_line_weekly_text(date), fn_line_daily2(date) from public, anon, authenticated;
grant execute on function fn_tai_apply(jsonb, date), fn_tci_ingest(jsonb, text), fn_line_weekly_text(date), fn_line_daily2(date) to service_role;
grant select, insert, update on tci_inbox to service_role;
grant execute on function rpc_get_tci_inbox(), rpc_tci_inbox_drop(jsonb), rpc_tci_inbox_issue(jsonb), rpc_get_weekly(jsonb) to anon, authenticated, service_role;
